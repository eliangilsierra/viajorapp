"""Viajorapp brand concept generator: geometry, colour maths, SVG builders.

Everything here is plain Python (stdlib only). All artwork is authored as vector
geometry in code; nothing is generated by an image model and nothing touches the
network. The wordmark is drawn from geometric primitives (no font files, no live
text), so the logo SVGs render identically everywhere.
"""
from __future__ import annotations

import math
from dataclasses import dataclass


# ----------------------------------------------------------------------------
# helpers
# ----------------------------------------------------------------------------
def f(n: float) -> str:
    s = f"{n:.2f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


@dataclass
class Tf:
    """Uniform scale + translate. Every coordinate is baked through this."""

    s: float = 1.0
    ox: float = 0.0
    oy: float = 0.0

    def x(self, v):
        return self.ox + v * self.s

    def y(self, v):
        return self.oy + v * self.s

    def l(self, v):
        return v * self.s

    def p(self, px, py):
        return f"{f(self.x(px))},{f(self.y(py))}"


# ----------------------------------------------------------------------------
# colour maths (WCAG 2.x)
# ----------------------------------------------------------------------------
def _lin(c: float) -> float:
    c /= 255
    return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4


def luminance(hex_: str) -> float:
    h = hex_.lstrip("#")
    r, g, b = (int(h[i : i + 2], 16) for i in (0, 2, 4))
    return 0.2126 * _lin(r) + 0.7152 * _lin(g) + 0.0722 * _lin(b)


def contrast(a: str, b: str) -> float:
    la, lb = luminance(a), luminance(b)
    hi, lo = max(la, lb), min(la, lb)
    return (hi + 0.05) / (lo + 0.05)


# ----------------------------------------------------------------------------
# geometric wordmark "Viajorapp" (hand-built letterforms, filled outlines)
# ----------------------------------------------------------------------------
def _ring(cx, cy, R, r, T: Tf) -> str:
    """Annulus: outer clockwise, inner counter-clockwise (non-zero fill)."""
    x0, x1 = T.x(cx - R), T.x(cx + R)
    y = T.y(cy)
    R_, r_ = T.l(R), T.l(r)
    d = f"M{f(x0)},{f(y)}A{f(R_)},{f(R_)} 0 1 1 {f(x1)},{f(y)}A{f(R_)},{f(R_)} 0 1 1 {f(x0)},{f(y)}Z"
    if r > 0:
        xi0, xi1 = T.x(cx - r), T.x(cx + r)
        d += f"M{f(xi0)},{f(y)}A{f(r_)},{f(r_)} 0 1 0 {f(xi1)},{f(y)}A{f(r_)},{f(r_)} 0 1 0 {f(xi0)},{f(y)}Z"
    return d


def _rect(x, y, w, h, T: Tf) -> str:
    return f"M{f(T.x(x))},{f(T.y(y))}H{f(T.x(x + w))}V{f(T.y(y + h))}H{f(T.x(x))}Z"


def _pol(angle_deg, cx, cy, rad):
    a = math.radians(angle_deg)
    return cx + rad * math.cos(a), cy + rad * math.sin(a)


@dataclass
class WordmarkStyle:
    weight: float  # stem thickness, x-height = 100
    gap: float  # gap between letters (x-height = 100)
    cap: float = 1.28  # V cap height / x-height
    desc: float = 0.55  # descender depth / x-height
    v_width: float = 1.12


def wordmark(text: str, st: WordmarkStyle, T: Tf, x0: float = 0.0):
    """Return (path_d, dots[(cx,cy,r)], width_in_units, extents).

    Baseline is y=0 in glyph units (up is negative). T maps glyph units to the
    destination, so geometry is baked at its final size.
    Supported letters: V i a j o r p (everything in "Viajorapp").
    """
    X = 100.0
    w = st.weight
    d = []
    dots = []
    x = x0
    dot_r = w * 0.64
    dot_cy = -X - 0.13 * X - dot_r
    first = True
    prev = ""
    for ch in text:
        kern = 0.0
        if prev == "V" and ch != "i":
            kern = -0.06 * X
        if ch == "j":
            kern = -0.34 * X  # hook tucks into descender space
        if prev == "r":
            kern = -0.10 * X
        if not first:
            x += st.gap + kern
        first = False
        if ch == "V":
            H = st.cap * X
            W = st.v_width * X
            b = w * 0.95  # flat apex width
            s = w * 1.18  # horizontal thickness of the arm at the top
            slope = (W / 2 - b / 2) / H  # dx/dy of outer edge
            dy_in = (W / 2 - s) / slope
            t = H - dy_in
            pts = [
                (x, -H),
                (x + s, -H),
                (x + W / 2, -t),
                (x + W - s, -H),
                (x + W, -H),
                (x + W / 2 + b / 2, 0),
                (x + W / 2 - b / 2, 0),
            ]
            d.append("M" + "L".join(T.p(px, py) for px, py in pts) + "Z")
            x += W
        elif ch == "i":
            d.append(_rect(x, -X, w, X, T))
            dots.append((T.x(x + w / 2), T.y(dot_cy), T.l(dot_r)))
            x += w
        elif ch in "oap":
            R = X / 2
            cx = x + R
            cy = -R
            d.append(_ring(cx, cy, R, R - w, T))
            if ch == "a":
                d.append(_rect(x + X - w, -X, w, X, T))
            if ch == "p":
                d.append(_rect(x, -X, w, X + st.desc * X, T))
            x += X
        elif ch == "j":
            rho = max(0.44 * X, w + 16)
            ang = 150
            span = (1 + math.cos(math.radians(30))) * rho  # leftmost reach
            sx = x + span - w  # stem left
            cx_, cy_ = sx + w - rho, st.desc * X - rho
            po = _pol(ang, cx_, cy_, rho)
            pi = _pol(ang, cx_, cy_, rho - w)
            rho_t, ri_t = T.l(rho), T.l(rho - w)
            d.append(
                f"M{T.p(sx + w, -X)}L{T.p(sx + w, cy_)}"
                f"A{f(rho_t)},{f(rho_t)} 0 0 1 {T.p(*po)}"
                f"L{T.p(*pi)}"
                f"A{f(ri_t)},{f(ri_t)} 0 0 0 {T.p(sx, cy_)}"
                f"L{T.p(sx, -X)}Z"
            )
            dots.append((T.x(sx + w / 2), T.y(dot_cy), T.l(dot_r)))
            x += span
        elif ch == "r":
            rho = max(0.42 * X, w + 14)
            cx_, cy_ = x + rho, -X + rho
            end = 300
            po = _pol(end, cx_, cy_, rho)
            pi = _pol(end, cx_, cy_, rho - w)
            rho_t, ri_t = T.l(rho), T.l(rho - w)
            d.append(_rect(x, -X, w, X, T))
            d.append(
                f"M{T.p(x, cy_)}A{f(rho_t)},{f(rho_t)} 0 0 1 {T.p(*po)}"
                f"L{T.p(*pi)}A{f(ri_t)},{f(ri_t)} 0 0 0 {T.p(x + w, cy_)}Z"
            )
            x += 1.5 * rho
        else:
            raise ValueError(f"glyph not drawn: {ch!r}")
        prev = ch
    ext = dict(
        top=-st.cap * X,
        bottom=st.desc * X,
        left=x0,
        right=x,
        xheight=X,
    )
    return "".join(d), dots, x - x0, ext


# ----------------------------------------------------------------------------
# rounded polygon + smooth blob helpers
# ----------------------------------------------------------------------------
def rounded_polygon(points, radii, T: Tf) -> str:
    """Closed polygon with per-corner rounding (quadratic arcs approximated by arcs)."""
    n = len(points)
    out = []
    for i in range(n):
        p0 = points[(i - 1) % n]
        p1 = points[i]
        p2 = points[(i + 1) % n]
        r = radii[i]
        v1 = (p0[0] - p1[0], p0[1] - p1[1])
        v2 = (p2[0] - p1[0], p2[1] - p1[1])
        l1, l2 = math.hypot(*v1), math.hypot(*v2)
        u1 = (v1[0] / l1, v1[1] / l1)
        u2 = (v2[0] / l2, v2[1] / l2)
        ang = math.acos(max(-1, min(1, u1[0] * u2[0] + u1[1] * u2[1])))
        t = r / math.tan(ang / 2) if r > 0 else 0
        t = min(t, l1 / 2, l2 / 2)
        rr = t * math.tan(ang / 2)
        a = (p1[0] + u1[0] * t, p1[1] + u1[1] * t)
        b = (p1[0] + u2[0] * t, p1[1] + u2[1] * t)
        cross = u1[0] * u2[1] - u1[1] * u2[0]
        sweep = 1 if cross < 0 else 0
        out.append(("M" if i == 0 else "L") + T.p(*a))
        if rr > 0:
            rt = T.l(rr)
            out.append(f"A{f(rt)},{f(rt)} 0 0 {sweep} {T.p(*b)}")
    return "".join(out) + "Z"


def blob_path(cx, cy, R, harmonics, T: Tf, n=8) -> str:
    """Smooth closed curve r(theta)=R*(1+sum a*cos(k*theta+ph)); n cubic segments."""
    pts = []
    for i in range(n):
        th = 2 * math.pi * i / n
        rad = R * (1 + sum(a * math.cos(k * th + ph) for k, a, ph in harmonics))
        pts.append((cx + rad * math.cos(th), cy + rad * math.sin(th)))
    d = f"M{T.p(*pts[0])}"
    for i in range(n):
        p0, p1, p2, p3 = pts[(i - 1) % n], pts[i], pts[(i + 1) % n], pts[(i + 2) % n]
        c1 = (p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6)
        c2 = (p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6)
        d += f"C{T.p(*c1)} {T.p(*c2)} {T.p(*p2)}"
    return d + "Z"


# ----------------------------------------------------------------------------
# symbols: each returns (svg_elements, bbox_in_512_space)
# colours: dict with keys body / accent
# ----------------------------------------------------------------------------
def sym_waypoint(T: Tf, col: dict) -> str:
    body, acc = col["body"], col["accent"]
    L = (118, 128)
    Rr = (394, 128)
    A = (256, 400)
    dx, dy = A[0] - L[0], A[1] - L[1]
    ln = math.hypot(dx, dy)
    start = (L[0] + dx / ln * 40, L[1] + dy / ln * 40)
    sw = T.l(64)
    route = (
        f'<path d="M{T.p(*start)}L{T.p(*A)}L{T.p(*Rr)}" fill="none" stroke="{body}" '
        f'stroke-width="{f(sw)}" stroke-linejoin="round" stroke-linecap="butt"/>'
    )
    ring = (
        f'<circle cx="{f(T.x(L[0]))}" cy="{f(T.y(L[1]))}" r="{f(T.l(40))}" fill="none" '
        f'stroke="{body}" stroke-width="{f(T.l(28))}"/>'
    )
    dot = f'<circle cx="{f(T.x(Rr[0]))}" cy="{f(T.y(Rr[1]))}" r="{f(T.l(46))}" fill="{acc}"/>'
    return f'<g id="symbol">{route}{ring}{dot}</g>'


def sym_keyhole(T: Tf, col: dict) -> str:
    """Keyhole whose slot is a road. Strictly one colour: the road's centre dashes are
    true cut-outs, so the symbol is identical in colour and one-colour use. The accent
    colour lives in the wordmark dots and the UI, not in this symbol."""
    body, acc = col["body"], col["accent"]
    head = f'<circle cx="{f(T.x(256))}" cy="{f(T.y(176))}" r="{f(T.l(104))}" fill="{body}"/>'
    pts = [(226, 262), (286, 262), (406, 450), (106, 450)]
    road = rounded_polygon(pts, [4, 4, 28, 28], T)
    slots = []
    for yt, yb, hwt, hwb in [(300, 324, 6, 8.5), (346, 380, 9.5, 13.5), (404, 442, 14.5, 20)]:
        sp = [(256 - hwt, yt), (256 + hwt, yt), (256 + hwb, yb), (256 - hwb, yb)]
        slots.append(rounded_polygon(sp, [2, 2, 3, 3], T))
    road_el = f'<path d="{road + "".join(slots)}" fill="{body}" fill-rule="evenodd"/>'
    dash_el = ""
    return f'<g id="symbol">{head}{road_el}{dash_el}</g>'


def blob_arc(cx, cy, R, harmonics, a0, a1, T: Tf, step=30) -> str:
    """Open smooth arc along the blob contour from angle a0 to a1 (degrees, clockwise on screen)."""
    def pt(deg):
        th = math.radians(deg)
        rad = R * (1 + sum(a * math.cos(k * th + ph) for k, a, ph in harmonics))
        return (cx + rad * math.cos(th), cy + rad * math.sin(th))

    n = max(2, int(round((a1 - a0) / step)))
    degs = [a0 + (a1 - a0) * i / n for i in range(n + 1)]
    pts = [pt(d) for d in degs]
    ext = [pt(a0 - (a1 - a0) / n)] + pts + [pt(a1 + (a1 - a0) / n)]
    d = f"M{T.p(*pts[0])}"
    for i in range(1, len(ext) - 2):
        p0, p1, p2, p3 = ext[i - 1], ext[i], ext[i + 1], ext[i + 2]
        c1 = (p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6)
        c2 = (p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6)
        d += f"C{T.p(*c1)} {T.p(*c2)} {T.p(*p2)}"
    return d


CONTOUR_H = [(2, 0.10, -0.7), (3, 0.075, 0.5)]


def sym_contour(T: Tf, col: dict) -> str:
    body, acc = col["body"], col["accent"]
    sw = f(T.l(40))
    r0 = blob_path(248, 270, 178, CONTOUR_H, T)
    r1 = blob_path(262, 262, 106, CONTOUR_H, T)
    ring0 = f'<path d="{r0}" fill="none" stroke="{body}" stroke-width="{sw}" stroke-linejoin="round"/>'
    ring1 = f'<path d="{r1}" fill="none" stroke="{body}" stroke-width="{sw}" stroke-linejoin="round"/>'
    tri = rounded_polygon([(272, 214), (318, 292), (226, 292)], [10, 10, 10], T)
    peak = f'<path d="{tri}" fill="{acc}"/>'
    return f'<g id="symbol">{ring0}{ring1}{peak}</g>'


SYMBOLS = {
    "waypoint": sym_waypoint,
    "keyhole": sym_keyhole,
    "contour": sym_contour,
}

# optical offsets (in 512 units) so the ink centre sits on the canvas centre
# (tuned in the QA loop; see QA_REPORT.md)
OPTICAL = {"waypoint": (2, 9), "keyhole": (0, -10), "contour": (-4, -18)}


# ----------------------------------------------------------------------------
# document builders
# ----------------------------------------------------------------------------
def svg_doc(viewbox: str, title: str, desc: str, body: str, bg: str | None = None) -> str:
    vb = viewbox.split()
    bgrect = (
        f'<rect width="{vb[2]}" height="{vb[3]}" fill="{bg}"/>' if bg else ""
    )
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{viewbox}" role="img">'
        f"<title>{title}</title><desc>{desc}</desc>{bgrect}{body}</svg>\n"
    )


def symbol_svg(name: str, col: dict, title: str) -> str:
    ox, oy = OPTICAL[name]
    return svg_doc(
        "0 0 512 512",
        title,
        "Viajorapp concept symbol, hand-authored vector geometry.",
        SYMBOLS[name](Tf(1, ox, oy), col),
    )


def app_icon_svg(name: str, bg: str | None, col: dict, scale: float, title: str) -> str:
    ox, oy = OPTICAL[name]
    # symbol is authored on a 512 canvas centred at (256,256) + optical offset
    T = Tf(scale, 512 - 256 * scale + ox * scale, 512 - 256 * scale + oy * scale)
    return svg_doc(
        "0 0 1024 1024",
        title,
        "Viajorapp concept app icon. Full-bleed background; artwork inside the Android adaptive-icon 66 percent safe circle.",
        SYMBOLS[name](T, col),
        bg=bg,
    )


def lockup_svg(name: str, st: WordmarkStyle, col: dict, text_col: str, title: str, text: str = "Viajorapp"):
    H = 160
    sym_h = 144
    k = sym_h / 512
    ox, oy = OPTICAL[name]
    Ts = Tf(k, 8 + ox * k, 8 + oy * k)
    sym = SYMBOLS[name](Ts, col)
    xh = 52.0  # x-height in lockup units
    kw = xh / 100
    base_y = 80 + xh / 2  # x-height band centred on the symbol centre
    x_start = 8 + sym_h + 30
    Tw = Tf(kw, x_start, base_y)
    d, dots, wun, ext = wordmark(text, st, Tw)
    width = math.ceil(x_start + wun * kw + 12)
    dots_svg = "".join(
        f'<circle cx="{f(cx)}" cy="{f(cy)}" r="{f(r)}" fill="{col["accent"]}"/>' for cx, cy, r in dots
    )
    wm = f'<g id="wordmark"><path d="{d}" fill="{text_col}"/>{dots_svg}</g>'
    return svg_doc(
        f"0 0 {width} {H}",
        title,
        "Horizontal lockup: symbol plus hand-drawn geometric wordmark, text converted to outlines.",
        sym + wm,
    )


def wordmark_only_paths(st: WordmarkStyle, height_px: float, x: float, base_y: float, col: dict, text_col: str, text="Viajorapp"):
    """Wordmark group at an arbitrary position/size (used in the mock UI)."""
    kw = height_px / 100
    Tw = Tf(kw, x, base_y)
    d, dots, wun, _ = wordmark(text, st, Tw)
    dots_svg = "".join(
        f'<circle cx="{f(cx)}" cy="{f(cy)}" r="{f(r)}" fill="{col["accent"]}"/>' for cx, cy, r in dots
    )
    return f'<path d="{d}" fill="{text_col}"/>{dots_svg}', wun * kw
